#!/usr/bin/env python3
"""Pull the CIMemories persona attributes into a flat, policy-facing statement list.

## Why this corpus, when a PII corpus was the obvious choice

The first plan was `pii-masking-200k` on the Hub. The Hub is unreachable from the authoring
host, and the workaround (fetch it on a runner) is blocked for a reason unrelated to the data:
Actions does not start jobs on this private repository. Rather than wait on that, the benchmark
this project already cites ships its own attributes *in the repository*, which api.github.com
serves.

That turns out to be the better corpus anyway. CIMemories' attributes are **candidate facts**
— one atomic statement per attribute, each tagged with an `information_domain` — which is
precisely the object the triage layer sees after extraction. LongMemEval utterances are
conversational text that has to be *turned into* candidate facts first; these already are.

## What the file deliberately does not contain

The benchmark's share/no-share labels. They are generated by GPT-5 at run time by
`data/persona_gold_labels.py`, and the README says so. Using them would make "the rules agree
with the labels" a statement about agreement with a model — which is the one thing this
measurement cannot afford, because a model is one of the two objects under comparison.

So the file carries only what is human-authored-in-the-loop-free: the statement, its domain,
and the persona id. The policy is ours, published in docs/02 section 5.3, and the rows are
filtered to those the policy *already* requires to stay private. No label of ours, no label of
theirs.
"""

from __future__ import annotations

import base64
import json
import subprocess
import sys

URL = "https://api.github.com/repos/facebookresearch/CIMemories/contents/data/data_openai_gpt-oss-120b.json"

# Domains whose attributes the published policy treats as private regardless of phrasing.
# Anything not listed is kept but flagged, so the run can report on it separately rather than
# silently widening the denominator.
PRIVATE_DOMAINS = {
    "health",
    "medical",
    "financial",
    "finance",
    "relationship",
    "family",
    "employment",
    "general",
}


def main(out: str) -> int:
    raw = subprocess.run(["curl", "-s", URL], capture_output=True, text=True, timeout=180).stdout
    payload = json.loads(raw)
    if "content" not in payload:
        print(f"fetch failed: {payload.get('message')}", file=sys.stderr)
        return 1
    personas = json.loads(base64.b64decode(payload["content"]))

    rows = []
    for index, persona in enumerate(personas):
        for name, attribute in (persona.get("information_attributes") or {}).items():
            statement = (attribute.get("memory_statement") or "").strip()
            if not statement:
                continue
            rows.append(
                {
                    "id": f"cim{index:02d}-{name}",
                    "attribute": name,
                    "domain": (attribute.get("information_domain") or "unknown").lower(),
                    "text": " ".join(statement.split()),
                    "persona": index,
                }
            )

    domains = {}
    for row in rows:
        domains[row["domain"]] = domains.get(row["domain"], 0) + 1

    with open(out, "w", encoding="utf-8") as handle:
        json.dump(
            {
                "source": "facebookresearch/CIMemories data/data_openai_gpt-oss-120b.json",
                "note": (
                    "Persona attributes only. The benchmark's own share/no-share labels are "
                    "GPT-5-generated and are deliberately not used here."
                ),
                "personas": len(personas),
                "statements": len(rows),
                "domains": dict(sorted(domains.items(), key=lambda kv: -kv[1])),
                "rows": rows,
            },
            handle,
            indent=2,
        )
    print(json.dumps({"personas": len(personas), "statements": len(rows), "domains": domains}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1] if len(sys.argv) > 1 else "statements.json"))
