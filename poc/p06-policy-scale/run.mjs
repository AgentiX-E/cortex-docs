#!/usr/bin/env node
/**
 * POC-6: does the rule layer hold on 1,467 candidate facts, or was n=60 flattering it?
 *
 * ## The measurement, stated so it can fail
 *
 * Every row is a persona attribute from CIMemories -- one atomic fact, already in the form the
 * triage layer receives after extraction. Under the published policy (docs/02 section 5.3) all
 * of them are private except possibly a few `general` ones, so the question is narrow and
 * answerable: **which of them does the rule layer publish?**
 *
 * A published row here is not a statistical fluctuation. It is a sentence like "I led the
 * project at work" being classified as organisational knowledge and sent to a shared store,
 * when the fact it carries is the speaker's employment history.
 *
 * ## Why the benchmark's own labels are not used
 *
 * They are generated by GPT-5 (see its README), and the claim under test is about a *rule layer
 * versus a model*. Agreeing with a model's labels would measure the wrong thing twice: once for
 * the rule layer, once for the corpus.
 *
 * ## The two numbers, and why both
 *
 *   leak      rows published to the shared store. Asymmetric: cannot be taken back.
 *   coverage  rows an explicit rule decided, i.e. rows that do not become a card. This is the
 *             number that needed a large n -- the queue length is a product cost, and 26.7%
 *             coverage on 60 rows was too small a sample to plan a UI around.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { table, wilsonInterval, wilsonUpper } from '../lib/stats.mjs';
import { classify, destination, RULE_TABLE } from '../p04-triage-rules/rules.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const results = join(HERE, '..', 'results');
const corpus = JSON.parse(readFileSync(join(HERE, 'statements.json'), 'utf8'));

// Domains where publishing one attribute is indefensible regardless of phrasing. The others are
// reported too, but they are not part of the forced denominator: `education` or `schedule` facts
// ("I take a Spanish class on Tuesdays") can legitimately be team knowledge.
const FORCED = new Set(['health', 'mental_health', 'finance', 'relationships', 'legal', 'housing', 'employment']);

const rows = corpus.rows.map((row) => ({ ...row, ...destination(row.text) }));
const forced = rows.filter((row) => FORCED.has(row.domain));

// A zero is only a measurement if the mechanism that produces ones was ever exercised. The
// publishing rule is `org-knowledge`; if its pattern never matches a single row, then "0 rows
// published" is a property of the corpus, not of the rule layer, and the Wilson bound printed
// over it would be a bound on nothing. This count is therefore taken *before* rule precedence,
// so a row the private rules vetoed still counts as an opportunity the ordering had to save.
const publishing = RULE_TABLE.find((rule) => rule.id === 'org-knowledge');
const publishingHits = rows.filter((row) => publishing.pattern.test(row.text));
const vetoedByPrivate = publishingHits.filter((row) => classify(row.text).scope !== 'shared');

const leaks = rows.filter((row) => row.destination === 'shared');
const forcedLeaks = forced.filter((row) => row.destination === 'shared');
const decided = rows.filter((row) => row.scope !== 'defer');

const byDomain = [...new Set(rows.map((row) => row.domain))]
  .sort()
  .map((domain) => {
    const subset = rows.filter((row) => row.domain === domain);
    const published = subset.filter((row) => row.destination === 'shared');
    const ruled = subset.filter((row) => row.scope !== 'defer');
    const rules = new Map();
    for (const row of subset) rules.set(row.rule ?? 'defer', (rules.get(row.rule ?? 'defer') ?? 0) + 1);
    return {
      domain,
      n: subset.length,
      leak: published.length,
      'leak upper': `${(wilsonUpper(published.length, subset.length) * 100).toFixed(1)}%`,
      coverage: `${((ruled.length / subset.length) * 100).toFixed(1)}%`,
      'top rule': [...rules.entries()].sort((a, b) => b[1] - a[1])[0].join(': '),
    };
  });

const summary = {
  generatedAt: new Date().toISOString(),
  source: corpus.source,
  corpus: { personas: corpus.personas, statements: corpus.statements, domains: corpus.domains },
  instrument: {
    publishingRuleHits: publishingHits.length,
    vetoedByPrivate: vetoedByPrivate.length,
    exercised: publishingHits.length > 0,
    note:
      publishingHits.length > 0
        ? 'the publishing rule fired, so the leak count is a measurement'
        : 'the publishing rule never fired on this corpus: the leak count is a structural zero and is NOT a bound',
  },
  pooled: {
    n: rows.length,
    leak: leaks.length,
    leakUpper: wilsonUpper(leaks.length, rows.length),
    coverage: decided.length / rows.length,
    coverageInterval: wilsonInterval(decided.length, rows.length),
  },
  forced: {
    n: forced.length,
    leak: forcedLeaks.length,
    leakUpper: wilsonUpper(forcedLeaks.length, forced.length),
    coverage: forced.filter((row) => row.scope !== 'defer').length / forced.length,
  },
  byDomain,
  leakExamples: leaks.slice(0, 12).map((row) => ({ id: row.id, rule: row.rule, domain: row.domain, text: row.text })),
};

writeFileSync(join(results, 'p06-policy-scale.json'), JSON.stringify(summary, null, 2));

const markdown = [
  '# POC-6: the rule layer on 1,467 candidate facts',
  '',
  `Corpus: ${corpus.personas} CIMemories personas, **${corpus.statements}** attribute statements, `
    + `${Object.keys(corpus.domains).length} domains. The benchmark's GPT-5-generated share labels are not used.`,
  '',
  '## What this corpus can and cannot measure',
  '',
  table(
    [
      {
        metric: 'publishing rule fired (opportunities to leak)',
        value: `${publishingHits.length} / ${rows.length}`,
        bound: `${vetoedByPrivate.length} of them vetoed by an earlier private rule`,
      },
      {
        metric: 'leak, all rows',
        value: `${leaks.length} / ${rows.length}`,
        bound: summary.instrument.exercised
          ? `Wilson 95% upper ${(summary.pooled.leakUpper * 100).toFixed(2)}%`
          : 'NOT MEASURED — the corpus never gave the publishing rule a chance',
      },
      {
        metric: 'coverage, all rows',
        value: `${(summary.pooled.coverage * 100).toFixed(1)}%`,
        bound: `95% CI ${(summary.pooled.coverageInterval[0] * 100).toFixed(1)}–${(summary.pooled.coverageInterval[1] * 100).toFixed(1)}%`,
      },
    ],
    ['metric', 'value', 'bound'],
  ),
  '',
  summary.instrument.exercised
    ? 'The leak count is a measurement: the publishing rule had opportunities and refused them.'
    : '**The leak count is not a measurement.** `org-knowledge` never matched a persona attribute, so this '
      + 'corpus cannot speak to false-share at all — and a Wilson bound over a mechanism that never ran '
      + 'would be a bound on nothing. What this corpus *does* measure is coverage, and it measures it '
      + 'well: 1,467 rows against 60.',
  '',
  '## By domain',
  '',
  table(
    byDomain,
    summary.instrument.exercised
      ? ['domain', 'n', 'leak', 'leak upper', 'coverage', 'top rule']
      : ['domain', 'n', 'leak', 'coverage', 'top rule'],
  ),
  '',
  '## Every published row, verbatim',
  '',
  ...(leaks.length === 0
    ? ['None.']
    : leaks.slice(0, 12).map((row) => `- \`${row.rule}\` · ${row.domain} · ${row.id} — ${row.text}`)),
  '',
].join('\n');

writeFileSync(join(results, 'p06-policy-scale.md'), markdown + '\n');
console.log(markdown);

if (leaks.length > 0) {
  console.error(`::warning::${leaks.length} of ${rows.length} candidate facts would be published`);
}
